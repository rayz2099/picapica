/** why: 只认中英；system 扫 languages 列表，中文优先，其余英文。 */
export function resolveUiLang(pref) {
  if (pref === "zh" || pref === "en") return pref;
  const list = [...(navigator.languages || []), navigator.language].filter(Boolean);
  for (const item of list) {
    if (String(item).toLowerCase().startsWith("zh")) return "zh";
  }
  return "en";
}

export function t(pref, key, vars) {
  const lang = resolveUiLang(pref);
  const table = lang === "zh" ? ZH : EN;
  let text = table[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, value);
    }
  }
  return text;
}

export function applyI18n(root, pref) {
  const lang = resolveUiLang(pref);
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.documentElement.dataset.lang = lang;
  document.title = t(pref, "title");
  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = t(pref, node.dataset.i18n ?? "");
  }
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    node.placeholder = t(pref, node.dataset.i18nPlaceholder ?? "");
  }
  for (const node of root.querySelectorAll("[data-i18n-title]")) {
    node.title = t(pref, node.dataset.i18nTitle ?? "");
  }
}
